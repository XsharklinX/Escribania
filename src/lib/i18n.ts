type Key = Key1 | Key2 | Key3 | Key4;

const DICTS: Record<Lang, Partial<Record<Key, string>>> = { es: { ...es, ...es2, ...es3, ...es4 }, en: { ...en, ...en2, ...en3, ...en4 } };

export type TKey = Key;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? DICTS.es[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.settings.lang);
  return (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
}

export function tNow(key: Key, vars?: Record<string, string | number>) {
  return translate(useStore.getState().settings.lang, key, vars);
}
